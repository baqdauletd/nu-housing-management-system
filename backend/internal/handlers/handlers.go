func UploadDocument(db *sql.DB, minioStore *database.MinIOStore) gin.HandlerFunc {
	return func(c *gin.Context) {
		applicationID, err := strconv.Atoi(c.PostForm("application_id"))
		if err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "invalid application_id"})
			return
		}

		docType := c.PostForm("type")
		if docType == "" {
			c.JSON(http.StatusBadRequest, gin.H{"error": "type is required"})
			return
		}

		file, err := c.FormFile("file")
		if err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "file is required"})
			return
		}

		if !strings.EqualFold(filepath.Ext(file.Filename), ".pdf") {
			c.JSON(http.StatusBadRequest, gin.H{"error": "only PDF files are allowed"})
			return
		}

		fileObj, err := file.Open()
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to open file"})
			return
		}
		defer fileObj.Close()

		if !authorizeApplicationAccess(c, db, applicationID) {
			return
		}

		pdfBytes, err := io.ReadAll(fileObj)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to read file"})
			return
		}

		contentType := file.Header.Get("Content-Type")
		if contentType == "" {
			contentType = "application/pdf"
		}

		objectName := fmt.Sprintf("applications/%d/%s.pdf", applicationID, docType)
		_, err = minioStore.Client.PutObject(
			c,
			minioStore.Bucket,
			objectName,
			bytes.NewReader(pdfBytes),
			int64(len(pdfBytes)),
			minio.PutObjectOptions{ContentType: contentType},
		)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to upload to storage", "details": err.Error()})
			return
		}

		originalFilename := file.Filename
		doc := models.Document{
			ApplicationID:    applicationID,
			Type:             docType,
			FileURL:          objectName,
			OriginalFilename: &originalFilename,
			ContentType:      &contentType,
		}
		id, err := database.SaveDocumentReplacingType(db, doc)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to save document into db", "details": err.Error()})
			return
		}

		go processUploadedDocumentAsync(db, applicationID, id, docType, append([]byte(nil), pdfBytes...))
		c.JSON(http.StatusCreated, gin.H{"document_id": id})
	}
}

func processUploadedDocumentAsync(db *sql.DB, applicationID, documentID int, docType string, pdfBytes []byte) {
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()

	if err := analyzeAndApplyDecision(ctx, db, applicationID, documentID, docType, pdfBytes); err != nil {
		fmt.Printf("background document analysis failed for application %d document %d: %v\n", applicationID, documentID, err)
	}
}

func analyzeAndApplyDecision(ctx context.Context, db *sql.DB, applicationID, documentID int, docType string, pdfBytes []byte) error {
	expectedType, ok := analysis.NormalizeDocumentType(docType)
	if !ok {
		result := analysis.ManualReviewResult(
			analysis.Request{
				DocumentID: documentID,
				Application: analysis.ApplicationContext{
					ApplicationID: applicationID,
				},
			},
			"",
			fmt.Sprintf("Manual review required because the uploaded document type %q is not supported for automatic Astana checks.", docType),
			"unsupported_document_type",
		)
		if err := database.UpsertDocumentAnalysis(db, result); err != nil {
			return err
		}
		return database.ApplyAutomatedDecision(db, applicationID)
	}

	app, err := database.GetApplicationByID(db, applicationID)
	if err != nil {
		return err
	}
	user, err := database.GetUserByID(db, app.StudentID)
	if err != nil {
		return err
	}

	analyzer := analysis.NewOpenAIAnalyzer(viper.GetString("OPENAI_API_KEY"), viper.GetString("OPENAI_MODEL"))
	req := analysis.Request{
		DocumentID:   documentID,
		ExpectedType: expectedType,
		PDFBytes:     pdfBytes,
		Application: analysis.ApplicationContext{
			ApplicationID:  app.ID,
			StudentID:      app.StudentID,
			StudentEmail:   user.Email,
			StudentNuID:    user.NuID,
			ApplicantType:  app.ApplicantType,
			StudentFIO:     app.FIO,
			PassportNumber: app.PassportNumber,
			Year:           app.Year,
			Major:          app.Major,
			Gender:         app.Gender,
			RoomPreference: app.RoomPreference,
			AdditionalInfo: app.AdditionalInfo,
			SubmittedAt:    app.SubmittedAt,
			UploadTime:     time.Now().UTC(),
		},
	}

	result, analyzeErr := analyzer.AnalyzeDocument(ctx, req)
	if err := database.UpsertDocumentAnalysis(db, result); err != nil {
		return err
	}
	if err := database.ApplyAutomatedDecision(db, applicationID); err != nil {
		return err
	}
	if analyzeErr != nil {
		return nil
	}
	return nil
}

