func SubmitApplication(db *sql.DB) gin.HandlerFunc {
	return func(c *gin.Context) {
		var body struct {
			ApplicantType  string `json:"applicant_type"`
			FIO            string `json:"fio"`
			PassportNumber string `json:"passport_number"`
			Year           int    `json:"year" binding:"required"`
			Major          string `json:"major" binding:"required"`
			Gender         string `json:"gender" binding:"required"`
			RoomPreference string `json:"room_preference"`
			AdditionalInfo string `json:"additional_info"`
		}
		if err := c.ShouldBindJSON(&body); err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "invalid input", "details": err.Error()})
			return
		}

		uid, ok := c.Get("user_id")
		if !ok {
			c.JSON(http.StatusUnauthorized, gin.H{"error": "user_id missing in token"})
			return
		}
		studentID := uid.(int)

		settings, err := database.GetSystemSettings(db)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to load application settings", "details": err.Error()})
			return
		}
		if !database.IsApplicationsOpen(settings, time.Now()) {
			c.JSON(http.StatusForbidden, gin.H{
				"error":                "applications are currently closed",
				"applications_enabled": settings.ApplicationsEnabled,
				"application_open":     formatDatePtr(settings.ApplicationOpen),
				"application_close":    formatDatePtr(settings.ApplicationClose),
			})
			return
		}

		app := models.Application{
			StudentID:      studentID,
			ApplicantType:  database.NormalizeApplicantTypeForSubmission(body.ApplicantType, body.AdditionalInfo),
			FIO:            strings.TrimSpace(body.FIO),
			PassportNumber: strings.TrimSpace(body.PassportNumber),
			Year:           body.Year,
			Major:          body.Major,
			Gender:         body.Gender,
			RoomPreference: body.RoomPreference,
			AdditionalInfo: body.AdditionalInfo,
		}
		if app.FIO == "" {
			app.FIO = database.ExtractFIOForSubmission(body.AdditionalInfo)
		}
		if app.PassportNumber == "" {
			app.PassportNumber = database.ExtractPassportNumberForSubmission(body.AdditionalInfo)
		}

		id, err := database.SubmitApplication(db, app)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to submit application", "details": err.Error()})
			return
		}
		c.JSON(http.StatusCreated, gin.H{"application_id": id})
	}
}

