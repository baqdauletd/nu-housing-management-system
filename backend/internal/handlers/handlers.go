func Register(db *sql.DB) gin.HandlerFunc {
	return func(c *gin.Context) {
		var user struct {
			NuID            string `json:"nu_id"`
			FirstName       string `json:"firstName"`
			LastName        string `json:"lastName"`
			Email           string `json:"email" binding:"required,email"`
			Password        string `json:"password" binding:"required,min=6"`
			ConfirmPassword string `json:"confirmPassword"`
			Phone           string `json:"phone"`
			Role            string `json:"role"`
		}
		if err := c.ShouldBindJSON(&user); err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "invalid input", "details": err.Error()})
			return
		}

		if user.ConfirmPassword != "" && user.Password != user.ConfirmPassword {
			c.JSON(http.StatusBadRequest, gin.H{"error": "passwords do not match"})
			return
		}

		role := strings.ToLower(user.Role)
		if role == "" {
			role = "student"
		}

		if role != "student" && role != "housing" {
			c.JSON(http.StatusBadRequest, gin.H{"error": "invalid role: only 'student' or 'housing' allowed"})
			return
		}

		nuID := strings.TrimSpace(user.NuID)
		autoGeneratedNuID := nuID == ""
		if autoGeneratedNuID {
			nuID = generateFallbackNuID()
		}

		roleID, err := database.GetRoleIDByName(db, role)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "role lookup failed"})
			return
		}

		if _, err := database.GetUserByEmail(db, user.Email); err == nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "email already used"})
			return
		}

		hashed, err := auth.HashPassword(user.Password)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to hash password"})
			return
		}

		u := models.User{
			NuID:         nuID,
			Email:        user.Email,
			PasswordHash: hashed,
			RoleID:       roleID,
			Phone:        &user.Phone,
		}
		id := 0
		for attempt := 0; attempt < 20; attempt++ {
			if autoGeneratedNuID && attempt > 0 {
				u.NuID = generateFallbackNuID()
			}

			id, err = database.CreateUser(db, u)
			if err == nil {
				break
			}

			if autoGeneratedNuID {
				if pqErr, ok := err.(*pq.Error); ok && pqErr.Code == "23505" && pqErr.Constraint == "users_nu_id_key" {
					continue
				}
			}

			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to create user", "details": err.Error()})
			return
		}
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "failed to create user", "details": "could not generate a unique student id"})
			return
		}

		// log registration
		db.Exec(`INSERT INTO audit_logs (actor_id, action, entity, entity_id) VALUES ($1, 'register', 'user', $1)`, id)

		c.JSON(http.StatusCreated, gin.H{"userId": id})
	}
}

func generateFallbackNuID() string {
	const (
		minSubmissionYear = 2018
		maxSubmissionYear = 2024
	)

	yearSpan := int64(maxSubmissionYear - minSubmissionYear + 1)
	yearOffset, err := rand.Int(rand.Reader, big.NewInt(yearSpan))
	if err != nil {
		return "202400000"
	}

	suffix, err := rand.Int(rand.Reader, big.NewInt(100000))
	if err != nil {
		return "202400000"
	}

	year := minSubmissionYear + int(yearOffset.Int64())
	return fmt.Sprintf("%04d%05d", year, suffix.Int64())
}

func Login(db *sql.DB) gin.HandlerFunc {
	return func(c *gin.Context) {
		var body struct {
			Email    string `json:"email" binding:"required,email"`
			Password string `json:"password" binding:"required"`
		}
		if err := c.ShouldBindJSON(&body); err != nil {
			c.JSON(http.StatusBadRequest, gin.H{"error": "invalid input"})
			return
		}

		user, err := database.ValidateUserCredentials(db, body.Email)
		if err != nil {
			// log failed login — no actor_id since user not found
			db.Exec(`INSERT INTO audit_logs (action, entity) VALUES ('login_failed', 'user')`)
			c.JSON(http.StatusUnauthorized, gin.H{"error": "no such email exists"})
			return
		}

		if err := auth.CheckPassword(user.PasswordHash, body.Password); err != nil {
			// log failed login — we know the user but wrong password
			db.Exec(`INSERT INTO audit_logs (actor_id, action, entity, entity_id) VALUES ($1, 'login_failed', 'user', $1)`, user.ID)
			c.JSON(http.StatusUnauthorized, gin.H{"error": "wrong password"})
			return
		}

		roleName, _ := database.GetRoleNameByID(db, user.RoleID)

		token, err := auth.GenerateToken(user.ID, roleName)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": "token generation failed"})
			return
		}

		// log successful login
		db.Exec(`INSERT INTO audit_logs (actor_id, action, entity, entity_id) VALUES ($1, 'login', 'user', $1)`, user.ID)

		c.JSON(http.StatusOK, gin.H{
			"token": token,
			"user": gin.H{
				"id":    user.ID,
				"nu_id": user.NuID,
				"email": user.Email,
				"role":  roleName,
				"phone": user.Phone,
			},
		})
	}
}

